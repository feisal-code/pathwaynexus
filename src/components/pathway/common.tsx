export function Notice({ children, tone = "info" }: { children: ReactNode; tone?: "info" | "warning" }) {
  const Icon = tone === "info" ? Info : AlertTriangle;
  return (
    <div
      className={cn(
        "flex gap-3 rounded-lg border px-4 py-3 text-sm leading-relaxed",
        tone === "info" ? "border-primary/20 bg-primary-soft text-secondary-foreground" : "border-warning/30 bg-warning-soft text-foreground",
      )}
    >
      <Icon className={cn("mt-0.5 size-4 shrink-0", tone === "info" ? "text-primary" : "text-warning")} aria-hidden="true" />
      <div>{children}</div>
    </div>
  );
}

export function MatchScore({ value, size = 64, label = "match" }: { value: number; size?: number; label?: string }) {
  const stroke = Math.max(4, size / 12);
  const r = (size - stroke) / 2;
  const c = 2 * Math.PI * r;
  const tone = value >= 85 ? "stroke-success" : value >= 65 ? "stroke-primary" : "stroke-warning";
  return (
    <div className="relative shrink-0" style={{ width: size, height: size }} role="img" aria-label={`${value}% ${label}`}>
      <svg width={size} height={size} className="-rotate-90">
        <circle cx={size / 2} cy={size / 2} r={r} fill="none" strokeWidth={stroke} className="stroke-muted" />
        <circle
          cx={size / 2}
          cy={size / 2}
          r={r}
          fill="none"
          strokeWidth={stroke}
          strokeLinecap="round"
          strokeDasharray={c}
          strokeDashoffset={c * (1 - value / 100)}
          className={cn(tone, "transition-[stroke-dashoffset] duration-700")}
        />
      </svg>
      <span className="absolute inset-0 flex flex-col items-center justify-center leading-none">
        <span className="font-display font-semibold" style={{ fontSize: size * 0.3 }}>
          {value}
          <span style={{ fontSize: size * 0.16 }}>%</span>
        </span>
      </span>
    </div>
  );
}

